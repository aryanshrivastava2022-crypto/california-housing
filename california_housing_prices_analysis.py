def make_random_splits(n_rows, seeds=SEEDS, test_size=TEST_FRACTION):
    """Return repeat, train-position, test-position tuples for row-level holdouts."""
    positions = np.arange(n_rows)
    return [
        (repeat, *train_test_split(
            positions, test_size=test_size, random_state=seed, shuffle=True
        ))
        for repeat, seed in enumerate(seeds, start=1)
    ]

def make_spatial_groups(frame, cell_degrees=SPATIAL_CELL_DEGREES):
    """Assign each row to a fixed-size longitude/latitude grid cell."""
    coordinates = frame[LOCATION_FEATURES]
    if coordinates.isna().any().any():
        raise ValueError("Spatial holdouts require non-missing longitude and latitude.")
    lon_cell = np.floor(coordinates["longitude"].to_numpy() / cell_degrees).astype("int64")
    lat_cell = np.floor(coordinates["latitude"].to_numpy() / cell_degrees).astype("int64")
    return np.char.add(np.char.add(lon_cell.astype(str), "_"), lat_cell.astype(str))

def make_spatial_splits(groups, seeds=SEEDS, test_size=TEST_FRACTION):
    """Return repeat, train-position, test-position tuples with whole cells held out."""
    positions = np.arange(len(groups))
    splits = []
    for repeat, seed in enumerate(seeds, start=1):
        splitter = GroupShuffleSplit(n_splits=1, test_size=test_size, random_state=seed)
        train_pos, test_pos = next(splitter.split(positions, groups=groups))
        splits.append((repeat, train_pos, test_pos))
    return splits

def regression_metrics(y_true, y_pred):
    """Return MAE and RMSE in the units of the target."""
    errors = np.asarray(y_true) - np.asarray(y_pred)
    return {
        "MAE": float(np.mean(np.abs(errors))),
        "RMSE": float(np.sqrt(np.mean(errors ** 2))),
    }

spatial_groups = make_spatial_groups(df)
