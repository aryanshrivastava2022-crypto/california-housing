MODEL_FEATURES = {
    "Income-only LinearRegression": BASELINE_FEATURES,
    "Random Forest (non-location)": NON_LOCATION_FEATURES,
    "Random Forest (+ coordinates)": LOCATION_FEATURE_SET,
}

def make_preprocessor(features):
    """Create an unfitted transformer for the requested predictor columns."""
    categorical = [feature for feature in features if feature in CATEGORICAL_FEATURES]
    numeric = [feature for feature in features if feature not in CATEGORICAL_FEATURES]
    transformers = []

    if numeric:
        numeric_pipeline = Pipeline([
            ("imputer", SimpleImputer(strategy="median")),
        ])
        transformers.append(("numeric", numeric_pipeline, numeric))

    if categorical:
        categorical_pipeline = Pipeline([
            ("imputer", SimpleImputer(strategy="most_frequent")),
            ("onehot", OneHotEncoder(handle_unknown="ignore")),
        ])
        transformers.append(("categorical", categorical_pipeline, categorical))

    return ColumnTransformer(transformers=transformers, remainder="drop")

def make_model_pipeline(model_name):
    """Return a fresh, unfitted preprocessing-and-estimator pipeline."""
    features = MODEL_FEATURES[model_name]
    if model_name == "Income-only LinearRegression":
        estimator = LinearRegression()
    else:
        estimator = RandomForestRegressor(**RF_PARAMS)

    return Pipeline([
        ("preprocess", make_preprocessor(features)),
        ("model", estimator),
    ])

pipeline_summary = []
for model_name, features in MODEL_FEATURES.items():
    pipeline = make_model_pipeline(model_name)
    pipeline_summary.append({
        "model": model_name,
        "predictor_count": len(features),
        "numeric_predictors": ", ".join(
            feature for feature in features if feature not in CATEGORICAL_FEATURES
        ),
        "categorical_predictors": ", ".join(
            feature for feature in features if feature in CATEGORICAL_FEATURES
        ) or "—",
        "pipeline_steps": " -> ".join(name for name, _ in pipeline.steps),
    })

print("Unfitted pipeline specifications (fit separately on each training split):")
